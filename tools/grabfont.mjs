// Reads glyph bitmaps for printable ASCII off the BUSY Bar's own screen, one character at a time.
// Output: a TS module with, per font, each glyph as column bitmasks (bit 0 = top row) plus its advance.
// Usage: node tools/grabfont.mjs <out.ts>
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(new URL("../marquee/package.json", import.meta.url));
const L = await import(pathToFileURL(require.resolve("@busy-app/busy-lib")).href);
const F = await import(pathToFileURL(require.resolve("@busy-app/busy-lib/fonts")).href);
for (const m of Object.values(F)) if (m && m.fonts) L.registerFontMaps(m);

const ADDR = `http://${process.env.BUSY_ADDR || "10.0.4.20"}/api`;
const FONTS = { normal: "bold", big: "extra_large" };
const X0 = 2;

async function draw(ch, font) {
  const el = { id: "g", type: "text", x: X0, y: 0, align: "top_left", text: ch, font, color: "#FFFFFFFF" };
  const r = await fetch(`${ADDR}/display/draw`, {
    method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ application_name: "grab", priority: 60, elements: [el] }),
  });
  if (!r.ok) throw new Error(`draw ${r.status} ${await r.text()}`);
  await new Promise((ok) => setTimeout(ok, 120));
  const px = Buffer.from(await (await fetch(`${ADDR}/screen?display=0`)).text(), "base64");
  return (x, y) => px[(y * 72 + x) * 3 + 1] > 128; // green channel of BGR
}

const out = {};
for (const [name, font] of Object.entries(FONTS)) {
  const glyphs = {};
  let top = 16, bottom = 0;
  for (let c = 32; c < 127; c++) {
    const ch = String.fromCharCode(c);
    const adv = L.textWidth(ch, font);
    const lit = await draw(ch, font);
    const cols = [];
    for (let x = X0; x < Math.min(72, X0 + adv + 2); x++) {
      let m = 0;
      for (let y = 0; y < 16; y++) if (lit(x, y)) { m |= 1 << y; top = Math.min(top, y); bottom = Math.max(bottom, y); }
      cols.push(m);
    }
    // Trim to the advance, keeping any ink that overhangs it.
    while (cols.length > adv && cols[cols.length - 1] === 0) cols.pop();
    glyphs[ch] = { a: adv, c: cols };
  }
  out[name] = { top, bottom, glyphs };
  console.log(`${name}: rows ${top}..${bottom}`);
}
await fetch(`${ADDR}/display/draw?application_name=grab`, { method: "DELETE" });

// Shift so row 0 is the topmost ink row; store compactly as "advance:col,col,..." per glyph.
let src = "// Generated by tools/grabfont.mjs from the BUSY Bar's own fonts. Do not edit.\n" +
  "// Based on Ark Pixel Font. Copyright (c) 2021, TakWolf; Copyright (c) 2024-2026, Flipper FZCO.\n" +
  "// Licensed under the SIL Open Font License, Version 1.1: see LICENSES/OFL-1.1.txt.\n";
src += "// Each glyph: advance, then column bitmasks with bit 0 at the font's top ink row.\n";
src += "export interface PixelFont { h: number; g: Record<string, [number, number[]]> }\n";
for (const [name, f] of Object.entries(out)) {
  const g = {};
  for (const [ch, { a, c }] of Object.entries(f.glyphs)) g[ch] = [a, c.map((m) => m >> f.top)];
  src += `export const ${name}: PixelFont = ${JSON.stringify({ h: f.bottom - f.top + 1, g })};\n`;
}
writeFileSync(process.argv[2], src);
console.log("wrote", process.argv[2]);
